import { stringify } from "yaml";
import type { Plan, Service, PortMapping, VolumeMapping } from "../../core/plan.js";
import { formatDuration, generatedRuntimeDir, parseDuration } from "./shell.js";

interface ComposeService {
  image?: string;
  build?: { context: string; dockerfile: string };
  container_name?: string;
  working_dir?: string;
  volumes?: string[];
  devices?: string[];
  cap_add?: string[];
  cap_drop?: string[];
  security_opt?: string[];
  environment?: Record<string, string>;
  networks?: string[];
  command?: string[];
  ports?: string[];
  depends_on?: Record<string, { condition: string }>;
  privileged?: boolean;
  healthcheck?: {
    test: string[];
    interval?: string;
    timeout?: string;
    retries?: number;
    start_period?: string;
  };
}

interface ComposeFile {
  services: Record<string, ComposeService>;
  volumes: Record<string, unknown>;
  networks: Record<string, unknown>;
}

export interface ComposePaths {
  buildContext?: string;
  dockerfile?: string;
  workspace?: string;
}

export function generateCompose(plan: Plan, paths: ComposePaths = {}): string {
  const services: Record<string, ComposeService> = {
    dev: devService(plan, paths),
  };

  const volumes: Record<string, unknown> = {};

  for (const svc of plan.runtime.services) {
    services[svc.name] = serviceCompose(svc);
    for (const vol of svc.volumes) {
      if (isNamedVolume(vol.host)) {
        volumes[vol.host] = {};
      }
    }
  }

  for (const namedVol of plan.runtime.namedVolumes) {
    volumes[namedVol.name] = {};
  }

  for (const volume of plan.runtime.volumes) {
    if (volume.type === "local" && volume.source && isNamedVolume(volume.source)) {
      volumes[volume.source] = {};
    }
  }

  if (plan.build.nodeModulesVolume) {
    volumes.node_modules = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("node_modules:/workspace/node_modules");
  }

  if (plan.build.venvVolume) {
    volumes.venv = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("venv:/workspace/.venv");
  }

  if (plan.build.vendorVolume) {
    volumes.vendor = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("vendor:/workspace/vendor");
  }

  const compose: ComposeFile = {
    services,
    volumes,
    networks: {
      biodome: {
        driver: "bridge",
      },
    },
  };

  const yaml = stringify(compose, { indent: 2 });
  return (
    "# Auto-generated by biodome\n# Source: .biodome/ directory\n# Do not edit this file directly; it will be regenerated.\n" +
    yaml +
    "\n"
  );
}

function devService(plan: Plan, paths: ComposePaths): ComposeService {
  const service: ComposeService = {
    build: {
      context: paths.buildContext ?? "..",
      dockerfile: paths.dockerfile ?? ".biodome-build/Dockerfile",
    },
    image: `${plan.project}-dev:latest`,
    container_name: `${plan.deployment?.deploymentId ?? plan.project}-dev`,
    working_dir: "/workspace",
    volumes: [`${paths.workspace ?? ".."}:/workspace`],
    networks: ["biodome"],
  };

  const hasMountedCloudVolume = plan.runtime.volumes.some((v) => v.type !== "local" && !v.proxy);
  if (hasMountedCloudVolume) {
    // FUSE-based cloud mounts need /dev/fuse and SYS_ADMIN capability.
    // Avoid privileged: true; use the minimum capability set instead.
    service.devices = ["/dev/fuse"];
    service.cap_add = ["SYS_ADMIN"];
    service.cap_drop = ["ALL"];
    service.security_opt = ["no-new-privileges:true"];
  }

  for (const volume of plan.runtime.volumes) {
    if (volume.type === "local" && volume.source && !volume.proxy) {
      service.volumes = service.volumes || [];
      service.volumes.push(`${volume.source}:${volume.target}`);
      if (volume.readOnly) {
        service.volumes[service.volumes.length - 1] += ":ro";
      }
    }
  }

  const environment: Record<string, string> = { ...plan.runtime.environment };

  // Passthrough env vars are resolved from the host at `up` time via compose
  // interpolation (${VAR}), so their values are never written into the image or
  // plan.json. This is the safe path for secrets.
  for (const envVar of plan.runtime.envVars) {
    if (!envVar.from) continue;
    if (envVar.scope === "build") continue;
    const ref = envVar.from.env;
    if (envVar.default !== undefined) {
      // Fall back to the default when the host var is unset or empty.
      environment[envVar.key] = `\${${ref}:-${envVar.default}}`;
    } else if (envVar.required) {
      // Fail `docker compose` loudly when a required var is missing.
      environment[envVar.key] = `\${${ref}:?${ref} is required by ${envVar.key}}`;
    } else {
      environment[envVar.key] = `\${${ref}}`;
    }
  }

  if (Object.keys(environment).length > 0) {
    service.environment = environment;
  }

  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");

  if (daemonProcesses.length > 0) {
    delete service.command;

    const ports: string[] = [];
    const seen = new Set<string>();
    for (const proc of daemonProcesses) {
      for (const p of proc.ports) {
        // The MCP server exposes action tools (exec_command, restart_process),
        // so publish it only on host loopback rather than all interfaces.
        const isMcpPort = plan.build.mcpEnabled && p.host === plan.build.mcpPort;
        const mapping = isMcpPort
          ? `127.0.0.1:${p.host}:${p.container}`
          : `${p.host}:${p.container}`;
        if (seen.has(mapping)) continue;
        seen.add(mapping);
        ports.push(mapping);
      }
    }
    if (ports.length > 0) {
      service.ports = ports;
    }

    const healthCheckedDaemons = daemonProcesses.filter((p) => p.healthCheck);
    if (healthCheckedDaemons.length > 0) {
      const intervals = healthCheckedDaemons.map((p) => parseDuration(p.healthCheck?.interval, 5));
      const timeouts = healthCheckedDaemons.map((p) => parseDuration(p.healthCheck?.timeout, 3));
      const retries = healthCheckedDaemons.map((p) => p.healthCheck?.retries ?? 3);
      const startPeriods = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.startPeriod, 10),
      );

      service.healthcheck = {
        test: ["CMD-SHELL", `sh ${generatedRuntimeDir(plan)}/healthchecks/all.sh`],
        interval: formatDuration(Math.min(...intervals)),
        timeout: formatDuration(
          Math.max(
            1,
            timeouts.reduce((a, b) => a + b, 0),
          ),
        ),
        retries: Math.min(...retries),
        start_period: formatDuration(Math.max(...startPeriods)),
      };
    }
  } else {
    service.command = ["sleep", "infinity"];
  }

  if (plan.runtime.services.length > 0) {
    service.depends_on = {};
    for (const svc of plan.runtime.services) {
      service.depends_on[svc.name] = {
        condition: svc.healthCheck ? "service_healthy" : "service_started",
      };
    }
  }

  return service;
}

function serviceCompose(svc: Service): ComposeService {
  const compose: ComposeService = {
    image: svc.image,
    container_name: svc.containerName,
    networks: svc.networks,
  };

  if (Object.keys(svc.environment).length > 0) {
    compose.environment = svc.environment;
  }

  if (svc.ports.length > 0) {
    compose.ports = svc.ports.map((p: PortMapping) => `${p.host}:${p.container}`);
  }

  if (svc.volumes.length > 0) {
    compose.volumes = svc.volumes.map((v: VolumeMapping) => `${v.host}:${v.container}`);
  }

  if (svc.healthCheck) {
    compose.healthcheck = {
      test: svc.healthCheck.test,
      interval: svc.healthCheck.interval,
      timeout: svc.healthCheck.timeout,
      retries: svc.healthCheck.retries,
      start_period: svc.healthCheck.startPeriod,
    };
  }

  return compose;
}

function isNamedVolume(host: string): boolean {
  return !host.startsWith("/") && !host.startsWith("./") && !host.startsWith("~");
}
