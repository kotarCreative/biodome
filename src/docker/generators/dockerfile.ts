import { identitiesOf, type Plan, type RuntimeIdentity } from "../../core/plan.js";
import { generatedRuntimeDir } from "./shell.js";
import { needsStartupScript } from "./startup.js";

export interface DockerfileOptions {
  /** Path to generated runtime files relative to the Docker build context. */
  generatedFilesPath?: string;
}

const MCP_PROXY_SDKS: Record<string, string> = {
  s3: "@aws-sdk/client-s3",
  gcs: "@google-cloud/storage",
  azure: "@azure/storage-blob",
};

function mcpProxySdks(plan: Plan): string[] {
  const packages = new Set<string>();
  for (const volume of plan.runtime.volumes) {
    if (volume.proxy && MCP_PROXY_SDKS[volume.type]) {
      packages.add(MCP_PROXY_SDKS[volume.type]);
    }
  }
  return Array.from(packages).sort();
}

function sortEnv(env: Record<string, string>): [string, string][] {
  return Object.keys(env)
    .sort()
    .map((k) => [k, env[k]]);
}

function identityCreationLines(identities: RuntimeIdentity[]): string[] {
  const lines = [
    "# Non-root runtime identities: user workloads never run as root.",
    "# supervisord starts as root only to initialize paths and setuid programs.",
  ];
  const byUid = [...identities].sort((a, b) => a.uid - b.uid);
  const byGid = [...identities].sort((a, b) => a.gid - b.gid);

  const shadowGroups = byGid.map(
    (identity) =>
      `groupadd -f --gid ${shellWord(String(identity.gid))} ${shellWord(identity.group)}`,
  );
  const shadowUsers = byUid.map((identity) =>
    [
      `useradd --uid ${shellWord(String(identity.uid))}`,
      `--gid ${shellWord(identity.group)}`,
      ...(identity.supplementaryGroups ?? []).map((group) => `--groups ${shellWord(group)}`),
      "--create-home",
      "--shell /bin/sh",
      shellWord(identity.user),
    ].join(" "),
  );

  const busyboxGroups = byGid.map(
    (identity) => `addgroup -g ${shellWord(String(identity.gid))} ${shellWord(identity.group)}`,
  );
  const busyboxUsers = byUid.map((identity) =>
    [
      `adduser -u ${shellWord(String(identity.uid))}`,
      `-G ${shellWord(identity.group)}`,
      "-D",
      "-s /bin/sh",
      shellWord(identity.user),
    ].join(" "),
  );
  const busyboxSupplementary = byUid.flatMap((identity) =>
    (identity.supplementaryGroups ?? []).map(
      (group) => `adduser ${shellWord(identity.user)} ${shellWord(group)}`,
    ),
  );

  lines.push(
    `RUN if command -v groupadd >/dev/null 2>&1; then \\`,
    `    ${[...shadowGroups, ...shadowUsers].join(" && \\\n    ")}; \\`,
    `elif command -v addgroup >/dev/null 2>&1; then \\`,
    `    ${[...busyboxGroups, ...busyboxUsers, ...busyboxSupplementary].join(" && \\\n    ")}; \\`,
    `else \\`,
    `    echo "No user management tooling available; cannot create runtime identities" >&2; exit 1; \\`,
    `fi`,
  );
  return lines;
}

function shellWord(value: string): string {
  return /^[a-zA-Z0-9_.:-]+$/.test(value) ? value : `'${value.replace(/'/g, "'\\''")}'`;
}

export function generateDockerfile(plan: Plan, options: DockerfileOptions = {}): string {
  const lines: string[] = [
    "# syntax=docker/dockerfile:1",
    "# Auto-generated by biodome",
    "# Multi-stage build: base -> deps -> dev",
    "#",
    "# BuildKit cache mounts are used for apt, npm, pnpm, pip, composer, go mod, and cargo",
    "# so iterative rebuilds skip downloading already-cached packages.",
    "# The dev stage starts from base and copies only the installed artifacts from",
    "# deps, so the final image does not include package manager caches or manifests.",
    "",
    `FROM ${plan.build.baseImage || "debian:12-slim"} AS base`,
    "",
  ];

  // Build-scoped values must also reach dependency installation in the deps stage.
  // JSON quoting preserves spaces, quotes and newlines without Docker expansion.
  for (const [key, value] of sortEnv(plan.build.environment)) {
    lines.push(`ENV ${key}=${JSON.stringify(value).replace(/\$/g, "\\$")}`);
  }
  if (Object.keys(plan.build.environment).length > 0) lines.push("");

  const aptPackages = [...plan.build.aptPackages];
  const hasDaemonProcesses = plan.runtime.processes.some((p) => p.mode === "daemon");
  const generatedFilesPath = options.generatedFilesPath ?? ".biodome-build";
  if (hasDaemonProcesses && !aptPackages.includes("supervisor")) {
    aptPackages.push("supervisor");
  }
  if (
    plan.deployment?.target.driver === "aws-ecs" &&
    plan.deployment.target.options.artifactBucket &&
    !aptPackages.includes("awscli")
  ) {
    aptPackages.push("awscli");
  }
  aptPackages.sort();

  if (aptPackages.length > 0) {
    lines.push("# Install system packages + service CLI clients.");
    lines.push("# Cache mounts keep the apt index and downloaded archives warm across");
    lines.push("# rebuilds; their contents stay outside image layers, so no cleanup");
    lines.push("# step is needed (deleting them here would force a full re-download).");
    lines.push("RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\");
    lines.push("    --mount=type=cache,target=/var/lib/apt/lists,sharing=locked \\");
    lines.push(
      `    apt-get update && apt-get install -y --no-install-recommends ${aptPackages.join(" \\\n    ")}`,
    );
    lines.push("");
  }

  if (plan.build.mcpEnabled) {
    lines.push("# Install the MCP SDK for the biodome-mcp server.");
    lines.push("# Installed under /node_modules so the ESM server at");
    lines.push("# /workspace/.biodome-build/mcp/server.js can resolve it. /node_modules is on");
    lines.push("# the module resolution path and is not shadowed by the /workspace mount.");
    lines.push(
      "RUN --mount=type=cache,target=/root/.npm npm install --prefix / @modelcontextprotocol/sdk@1.30.0 effect@4.0.0-beta.103",
    );
    lines.push("");

    const proxySdks = mcpProxySdks(plan);
    if (proxySdks.length > 0) {
      lines.push("# Install provider SDKs for MCP proxy volumes.");
      lines.push("# Only the SDKs actually used by declared proxy volumes are installed.");
      lines.push(
        `RUN --mount=type=cache,target=/root/.npm npm install --prefix / ${proxySdks.join(" ")}`,
      );
      lines.push("");
    }
  }

  for (const snippet of plan.build.runtimeInstalls) {
    lines.push(snippet);
  }
  if (plan.build.runtimeInstalls.length > 0) {
    lines.push("");
  }

  for (const snippet of plan.build.languageSnippets) {
    lines.push(snippet);
  }
  if (plan.build.languageSnippets.length > 0) {
    lines.push("");
  }

  lines.push(
    "# Identity mapping and bounded non-root commands also work on Alpine bases.",
    "RUN if command -v apk >/dev/null 2>&1; then apk add --no-cache shadow util-linux coreutils; fi",
    "",
  );

  lines.push(...identityCreationLines(identitiesOf(plan)));
  lines.push("");

  lines.push("# Stage 2: deps");
  lines.push("FROM base AS deps");
  lines.push("WORKDIR /workspace");
  lines.push("");

  const manifestFiles = plan.build.dependencyFiles;
  if (manifestFiles.length > 0) {
    lines.push(`COPY ${manifestFiles.join(" ")} /workspace/`);
    lines.push("");
  }

  for (const install of plan.build.dependencyInstalls) {
    lines.push(install.command);
    lines.push("");
  }

  lines.push("# Stage 3: dev");
  lines.push("FROM base AS dev");
  lines.push("WORKDIR /workspace");
  lines.push("");

  for (const artifact of plan.build.copyArtifacts) {
    lines.push(artifact.lines.join("\n"));
    lines.push("");
  }

  if (plan.deployment?.target.driver === "aws-ecs") {
    // Remote providers have no host bind mount: the repository workspace is
    // uploaded as the build context and materialized inside the immutable
    // image. Excluded trees (.git, node_modules, .env, ...) stay out via the
    // generated Dockerfile-specific ignore file, regardless of a repository's
    // own .dockerignore; dependency artifacts copied above are not shadowed.
    // Generated target files are layered on top afterwards.
    lines.push("# Materialize the declared upload workspace inside the image.");
    lines.push("COPY . /workspace/");
    lines.push("");
  }

  if (options.generatedFilesPath) {
    lines.push("# Copy target-scoped runtime files required without a host workspace mount.");
    lines.push(`COPY ${generatedFilesPath}/ ${generatedRuntimeDir(plan)}/`);
    lines.push("");
  }

  const identities = identitiesOf(plan);
  const runtimeIdentity =
    identities.find((identity) => identity.role === "runtime") ?? identities[0];
  if (runtimeIdentity) {
    // Image-borne workspace content (dependency installs, generated runtime
    // files) belongs to the workload identity. Bind-mounted host sources are
    // handled by the startup script without touching host ownership. A single
    // RUN keeps it to one tree walk over /workspace.
    lines.push("# Assign ownership only to image-borne workspace and generated paths.");
    lines.push(
      `RUN chown -R ${shellWord(`${runtimeIdentity.user}:${runtimeIdentity.group}`)} /workspace \\`,
    );
    lines.push(`    && chmod -R g+rX /workspace`);
    lines.push("");
  }

  const hasStartupScript = needsStartupScript(plan);
  if (!hasStartupScript && runtimeIdentity) {
    // No supervised lifecycle to initialize: interactive sessions run directly
    // as the non-root workload user.
    lines.push(`USER ${shellWord(runtimeIdentity.user)}`);
    lines.push("");
  }

  if (hasStartupScript) {
    if (!options.generatedFilesPath) {
      lines.push("# Copy the managed-process startup script.");
      lines.push(`COPY ${generatedFilesPath}/startup.sh ${generatedRuntimeDir(plan)}/startup.sh`);
      lines.push("");
    }
    lines.push("# Run lifecycle hooks, then start managed processes when declared.");
    lines.push(`CMD ["sh", "${generatedRuntimeDir(plan)}/startup.sh"]`);
  } else {
    lines.push("# Source code is mounted at runtime via 'docker run -v .:/workspace'");
    lines.push('CMD ["bash"]');
  }

  return lines.join("\n") + "\n";
}
