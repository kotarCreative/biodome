import type { Plan } from "../../core/plan.js";
import { generatedRuntimeDir } from "./shell.js";

export interface DockerfileOptions {
  /** Path to generated runtime files relative to the Docker build context. */
  generatedFilesPath?: string;
}

const MCP_PROXY_SDKS: Record<string, string> = {
  s3: "@aws-sdk/client-s3",
  gcs: "@google-cloud/storage",
  azure: "@azure/storage-blob",
};

function mcpProxySdks(plan: Plan): string[] {
  const packages = new Set<string>();
  for (const volume of plan.runtime.volumes) {
    if (volume.proxy && MCP_PROXY_SDKS[volume.type]) {
      packages.add(MCP_PROXY_SDKS[volume.type]);
    }
  }
  return Array.from(packages).sort();
}

function sortEnv(env: Record<string, string>): [string, string][] {
  return Object.keys(env)
    .sort()
    .map((k) => [k, env[k]]);
}

export function generateDockerfile(plan: Plan, options: DockerfileOptions = {}): string {
  const lines: string[] = [
    "# syntax=docker/dockerfile:1",
    "# Auto-generated by biodome",
    "# Multi-stage build: base -> deps -> dev",
    "#",
    "# BuildKit cache mounts are used for apt, npm, pnpm, pip, composer, go mod, and cargo",
    "# so iterative rebuilds skip downloading already-cached packages.",
    "# The dev stage starts from base and copies only the installed artifacts from",
    "# deps, so the final image does not include package manager caches or manifests.",
    "",
    `FROM ${plan.build.baseImage || "debian:12-slim"} AS base`,
    "",
  ];

  const aptPackages = [...plan.build.aptPackages];
  const hasDaemonProcesses = plan.runtime.processes.some((p) => p.mode === "daemon");
  const generatedFilesPath = options.generatedFilesPath ?? ".biodome-build";
  if (hasDaemonProcesses && !aptPackages.includes("supervisor")) {
    aptPackages.push("supervisor");
  }
  if (
    plan.deployment?.target.driver === "aws-ecs" &&
    plan.deployment.target.options.artifactBucket &&
    !aptPackages.includes("awscli")
  ) {
    aptPackages.push("awscli");
  }
  aptPackages.sort();

  if (aptPackages.length > 0) {
    lines.push("# Install system packages + service CLI clients.");
    lines.push("# Cache mounts prevent re-downloading the apt index every rebuild.");
    lines.push("RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\");
    lines.push("    --mount=type=cache,target=/var/lib/apt/lists,sharing=locked \\");
    lines.push("    apt-get update && apt-get install -y --no-install-recommends \\");
    for (const pkg of aptPackages) {
      lines.push(`    ${pkg} \\`);
    }
    lines.push("    && rm -rf /var/lib/apt/lists/* /var/cache/apt/archives/*");
    lines.push("");
  }

  if (plan.build.mcpEnabled) {
    lines.push("# Install the MCP SDK for the biodome-mcp server.");
    lines.push("# Installed under /node_modules so the ESM server at");
    lines.push("# /workspace/.biodome-build/mcp/server.js can resolve it. /node_modules is on");
    lines.push("# the module resolution path and is not shadowed by the /workspace mount.");
    lines.push("RUN npm install --prefix / @modelcontextprotocol/sdk");
    lines.push("");

    const proxySdks = mcpProxySdks(plan);
    if (proxySdks.length > 0) {
      lines.push("# Install provider SDKs for MCP proxy volumes.");
      lines.push("# Only the SDKs actually used by declared proxy volumes are installed.");
      lines.push(`RUN npm install --prefix / ${proxySdks.join(" ")}`);
      lines.push("");
    }
  }

  for (const snippet of plan.build.runtimeInstalls) {
    lines.push(snippet);
  }
  if (plan.build.runtimeInstalls.length > 0) {
    lines.push("");
  }

  for (const snippet of plan.build.languageSnippets) {
    lines.push(snippet);
  }
  if (plan.build.languageSnippets.length > 0) {
    lines.push("");
  }

  lines.push("# Stage 2: deps");
  lines.push("FROM base AS deps");
  lines.push("WORKDIR /workspace");
  lines.push("");

  const manifestFiles = plan.build.dependencyFiles;
  if (manifestFiles.length > 0) {
    lines.push(`COPY ${manifestFiles.join(" ")} /workspace/`);
    lines.push("");
  }

  for (const install of plan.build.dependencyInstalls) {
    lines.push(install.command);
    lines.push("");
  }

  lines.push("# Stage 3: dev");
  lines.push("FROM base AS dev");
  lines.push("WORKDIR /workspace");
  lines.push("");

  for (const artifact of plan.build.copyArtifacts) {
    lines.push(artifact.lines.join("\n"));
    lines.push("");
  }

  if (options.generatedFilesPath) {
    lines.push("# Copy target-scoped runtime files required without a host workspace mount.");
    lines.push(`COPY ${generatedFilesPath}/ ${generatedRuntimeDir(plan)}/`);
    lines.push("");
  }

  if (Object.keys(plan.build.environment).length > 0) {
    const envVars = sortEnv(plan.build.environment);
    lines.push("ENV ");
    for (let i = 0; i < envVars.length; i++) {
      const [k, v] = envVars[i];
      const prefix = i > 0 ? "    " : "";
      const suffix = i < envVars.length - 1 ? " \\" : "";
      lines.push(`${prefix}${k}=${v}${suffix}`);
    }
    lines.push("");
  }

  if (hasDaemonProcesses || plan.runtime.processes.some((p) => p.mode === "oneshot")) {
    if (!options.generatedFilesPath) {
      lines.push("# Copy the managed-process startup script.");
      lines.push(`COPY ${generatedFilesPath}/startup.sh ${generatedRuntimeDir(plan)}/startup.sh`);
      lines.push("");
    }
    lines.push("# Run lifecycle hooks, then start managed processes when declared.");
    lines.push(`CMD ["sh", "${generatedRuntimeDir(plan)}/startup.sh"]`);
  } else {
    lines.push("# Source code is mounted at runtime via 'docker run -v .:/workspace'");
    lines.push('CMD ["bash"]');
  }

  return lines.join("\n") + "\n";
}
