import type { Plan } from "../../core/plan.js";
import { identityForProcess, identitiesOf } from "../../core/plan.js";
import { systemUserForService } from "../../core/services.js";
import {
  assertIdentifier,
  generatedRuntimeDir,
  parseDuration,
  shellQuote,
  SUPERVISOR_LOG_DIR_ENV,
  supervisorLogDir,
} from "./shell.js";

function quoteSupervisordEnv(value: string): string {
  // supervisord needs literal % doubled, and double quotes escaped. Newlines
  // are flattened: an INI value cannot span lines, and a raw newline would
  // start a new config directive (builders reject them upstream; this is the
  // generator-level backstop).
  return `"${value.replace(/\r\n?/g, " ").replace(/%/g, "%%").replace(/"/g, '\\"')}"`;
}

function supervisordEnvValue(value: string): string {
  // `${VAR}` placeholders from the plan must become supervisord's own expansion
  // syntax; passing them through literally would hand processes the raw string.
  const ref = value.match(/^\$\{([A-Za-z_][A-Za-z0-9_]*)\}$/);
  if (ref) return `"%(ENV_${ref[1]})s"`;
  return quoteSupervisordEnv(value);
}

function sortEnv(env: Record<string, string>): [string, string][] {
  return Object.keys(env)
    .sort()
    .map((k) => [k, env[k]]);
}
/**
 * Resolve the OS user a supervised program runs as. Biodome-generated
 * infrastructure categories (health monitors, in-container database servers)
 * keep dedicated users; everything else uses the process's generated identity.
 */
function supervisorUser(plan: Plan, proc: Plan["runtime"]["processes"][number]): string {
  const service = plan.runtime.services.find(
    (candidate) => `${candidate.name}-server` === proc.name,
  );
  if (service) {
    const systemUser = systemUserForService(service.type);
    if (systemUser) return systemUser;
  }
  return identityForProcess(plan, proc).user;
}

/**
 * True for in-container database servers. Their readiness is gated by the
 * startup script's bootstrap health wait, so supervisord should mark them
 * RUNNING immediately instead of blocking `supervisorctl start` on the
 * default one-second startsecs window.
 */
function isServiceServer(plan: Plan, proc: Plan["runtime"]["processes"][number]): boolean {
  return plan.runtime.services.some((candidate) => `${candidate.name}-server` === proc.name);
}

export function generateSupervisordConf(plan: Plan): string {
  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");
  if (daemonProcesses.length === 0) {
    return "";
  }

  const logDir = supervisorLogDir(plan);
  const runtimeGroup =
    identitiesOf(plan).find((identity) => identity.role === "runtime")?.group ?? "biodome";
  const lines: string[] = [
    "; Auto-generated by biodome",
    "; Managed processes declared in biodome/features/*.js",
    "[supervisord]",
    "nodaemon=true",
    `logfile=${logDir}/supervisord.log`,
    `pidfile=${logDir}/supervisord.pid`,
    // Elevated only to initialize paths and setuid programs below; it never
    // runs user workloads as root.
    "user=root",
    "",
    "[unix_http_server]",
    `file=${logDir}/supervisor.sock`,
    // The MCP identity controls processes through this socket; grant access to
    // the shared runtime group rather than leaving it root-only.
    "chmod=0770",
    `chown=root:${shellQuote(runtimeGroup)}`,
    "",
    "[supervisorctl]",
    `serverurl=unix://${logDir}/supervisor.sock`,
    "",
    "[rpcinterface:supervisor]",
    "supervisor.rpcinterface_factory = supervisor.rpcinterface:make_main_rpcinterface",
    "",
  ];

  for (const proc of daemonProcesses) {
    assertIdentifier(proc.name, "process name");
    lines.push(`[program:${proc.name}]`);
    const cmd = proc.command.map(shellQuote).join(" ");
    lines.push(`command=${cmd}`);
    if (proc.workingDir) {
      // Quoted like env values so spaces and % never break the INI directive.
      lines.push(`directory=${quoteSupervisordEnv(proc.workingDir)}`);
    }
    // User workloads, MCP, and mount helpers each run as their generated
    // non-root identity. Health monitors are biodome infrastructure that must
    // reach the supervisor socket to restart failing programs. In-container
    // database servers run as their package-created dedicated system user.
    lines.push(`user=${shellQuote(supervisorUser(plan, proc))}`);
    lines.push("autostart=false");
    lines.push("autorestart=true");
    lines.push("startretries=10");
    if (isServiceServer(plan, proc)) {
      // Readiness is gated by the startup script's bootstrap health wait;
      // marking RUNNING immediately avoids a fixed startsecs delay on every
      // cold start.
      lines.push("startsecs=0");
    }
    lines.push(`stdout_logfile=${logDir}/${proc.name}.log`);
    lines.push(`stderr_logfile=${logDir}/${proc.name}.log`);
    // Expose the log dir to managed processes so the biodome-mcp server can
    // resolve the same paths for get_logs without importing generator code.
    const envVars = sortEnv({ ...proc.environment, [SUPERVISOR_LOG_DIR_ENV]: logDir });
    lines.push(
      `environment=${envVars.map(([k, v]) => `${k}=${supervisordEnvValue(v)}`).join(",")}`,
    );
    lines.push("");

    if (proc.healthCheck) {
      const startPeriod = proc.healthCheck.startPeriod || "5s";
      const monitorScript = shellQuote(
        `${generatedRuntimeDir(plan)}/healthchecks/${proc.name}-monitor.sh`,
      );
      lines.push(`[program:${proc.name}-healthcheck]`);
      lines.push(`command=sh ${monitorScript}`);
      lines.push("user=root");
      lines.push("autostart=false");
      lines.push("autorestart=true");
      lines.push(`startsecs=${Math.ceil(parseDuration(startPeriod, 5))}`);
      lines.push(`stdout_logfile=${logDir}/${proc.name}-healthcheck.log`);
      lines.push(`stderr_logfile=${logDir}/${proc.name}-healthcheck.log`);
      lines.push("");
    }
  }

  return lines.join("\n") + "\n";
}
