import { stringify } from "yaml";
import { Plan, Process, Service, ProcessHealthCheck, PortMapping, VolumeMapping } from "../core/plan.js";

interface ComposeService {
  image?: string;
  build?: { context: string; dockerfile: string };
  container_name?: string;
  working_dir?: string;
  volumes?: string[];
  environment?: Record<string, string>;
  networks?: string[];
  command?: string[];
  ports?: string[];
  depends_on?: Record<string, { condition: string }>;
  healthcheck?: {
    test: string[];
    interval?: string;
    timeout?: string;
    retries?: number;
    start_period?: string;
  };
}

interface ComposeFile {
  services: Record<string, ComposeService>;
  volumes: Record<string, unknown>;
  networks: Record<string, unknown>;
}

export function generateDockerfile(plan: Plan): string {
  const lines: string[] = [
    "# syntax=docker/dockerfile:1",
    "# Auto-generated by biodome",
    "# Multi-stage build: base -> deps -> dev",
    "#",
    "# BuildKit cache mounts are used for apt, npm, pnpm, pip, go mod, and cargo",
    "# so iterative rebuilds skip downloading already-cached packages.",
    "# The dev stage starts from base and copies only the installed artifacts from",
    "# deps, so the final image does not include package manager caches or manifests.",
    "",
    `FROM ${plan.build.baseImage || "debian:12-slim"} AS base`,
    "",
  ];

  const aptPackages = [...plan.build.aptPackages];
  const hasDaemonProcesses = plan.runtime.processes.some((p) => p.mode === "daemon");
  if (hasDaemonProcesses && !aptPackages.includes("supervisor")) {
    aptPackages.push("supervisor");
  }
  aptPackages.sort();

  if (aptPackages.length > 0) {
    lines.push("# Install system packages + service CLI clients.");
    lines.push("# Cache mounts prevent re-downloading the apt index every rebuild.");
    lines.push("RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\");
    lines.push("    --mount=type=cache,target=/var/lib/apt/lists,sharing=locked \\");
    lines.push("    apt-get update && apt-get install -y --no-install-recommends \\");
    for (const pkg of aptPackages) {
      lines.push(`    ${pkg} \\`);
    }
    lines.push("    && rm -rf /var/lib/apt/lists/* /var/cache/apt/archives/*");
    lines.push("");
  }

  for (const snippet of plan.build.runtimeInstalls) {
    lines.push(snippet);
  }
  if (plan.build.runtimeInstalls.length > 0) {
    lines.push("");
  }

  for (const snippet of plan.build.languageSnippets) {
    lines.push(snippet);
  }
  if (plan.build.languageSnippets.length > 0) {
    lines.push("");
  }

  lines.push("# Stage 2: deps");
  lines.push("FROM base AS deps");
  lines.push("WORKDIR /workspace");
  lines.push("");

  const manifestFiles = plan.build.dependencyFiles;
  if (manifestFiles.length > 0) {
    lines.push(`COPY ${manifestFiles.join(" ")} /workspace/`);
    lines.push("");
  }

  for (const install of plan.build.dependencyInstalls) {
    lines.push(install.command);
    lines.push("");
  }

  lines.push("# Stage 3: dev");
  lines.push("FROM base AS dev");
  lines.push("WORKDIR /workspace");
  lines.push("");

  for (const artifact of plan.build.copyArtifacts) {
    lines.push(artifact.lines.join("\n"));
    lines.push("");
  }

  if (Object.keys(plan.build.environment).length > 0) {
    const envVars = sortEnv(plan.build.environment);
    lines.push("ENV ");
    for (let i = 0; i < envVars.length; i++) {
      const [k, v] = envVars[i];
      const prefix = i > 0 ? "    " : "";
      const suffix = i < envVars.length - 1 ? " \\" : "";
      lines.push(`${prefix}${k}=${v}${suffix}`);
    }
    lines.push("");
  }

  if (hasDaemonProcesses) {
    lines.push("# Copy supervisord configuration for managed processes.");
    lines.push("COPY .biodome/supervisord.conf /workspace/.biodome/supervisord.conf");
    lines.push("");
    lines.push("# Start managed processes via supervisord.");
    lines.push('CMD ["supervisord", "-c", "/workspace/.biodome/supervisord.conf"]');
  } else {
    lines.push("# Source code is mounted at runtime via 'docker run -v .:/workspace'");
    lines.push('CMD ["bash"]');
  }

  return lines.join("\n") + "\n";
}

export function generateHealthcheckScripts(plan: Plan): Record<string, string> {
  const scripts: Record<string, string> = {};
  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");
  for (const proc of daemonProcesses) {
    if (proc.healthCheck) {
      scripts[`${proc.name}.sh`] = processHealthCheckScript(proc);
      scripts[`${proc.name}-monitor.sh`] = processHealthMonitorScript(proc);
    }
  }
  const all = aggregateHealthCheckScript(plan.runtime.processes);
  if (all) {
    scripts["all.sh"] = all;
  }
  return scripts;
}

export function generateSupervisordConf(plan: Plan): string {
  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");
  if (daemonProcesses.length === 0) {
    return "";
  }

  const lines: string[] = [
    "; Auto-generated by biodome",
    "; Managed processes declared in biodome/features/*.js",
    "[supervisord]",
    "nodaemon=true",
    "logfile=/tmp/supervisord.log",
    "pidfile=/tmp/supervisord.pid",
    "user=root",
    "",
    "[unix_http_server]",
    "file=/tmp/supervisor.sock",
    "",
    "[supervisorctl]",
    "serverurl=unix:///tmp/supervisor.sock",
    "",
    "[rpcinterface:supervisor]",
    "supervisor.rpcinterface_factory = supervisor.rpcinterface:make_main_rpcinterface",
    "",
  ];

  for (const proc of daemonProcesses) {
    lines.push(`[program:${proc.name}]`);
    const cmd = proc.command.join(" ");
    lines.push(`command=${cmd}`);
    if (proc.workingDir) {
      lines.push(`directory=${proc.workingDir}`);
    }
    lines.push("autostart=true");
    lines.push("autorestart=true");
    lines.push("startretries=10");
    lines.push(`stdout_logfile=/tmp/${proc.name}.log`);
    lines.push(`stderr_logfile=/tmp/${proc.name}.log`);
    if (Object.keys(proc.environment).length > 0) {
      const envVars = sortEnv(proc.environment);
      lines.push(
        `environment=${envVars.map(([k, v]) => `${k}=${quoteSupervisordEnv(v)}`).join(",")}`
      );
    }
    lines.push("");

    if (proc.healthCheck) {
      const startPeriod = proc.healthCheck.startPeriod || "5s";
      lines.push(`[program:${proc.name}-healthcheck]`);
      lines.push(
        `command=sh /workspace/.biodome/healthchecks/${proc.name}-monitor.sh`
      );
      lines.push("autostart=true");
      lines.push("autorestart=true");
      lines.push(`startsecs=${Math.ceil(parseDuration(startPeriod, 5))}`);
      lines.push(`stdout_logfile=/tmp/${proc.name}-healthcheck.log`);
      lines.push(`stderr_logfile=/tmp/${proc.name}-healthcheck.log`);
      lines.push("");
    }
  }

  return lines.join("\n") + "\n";
}

export function generateDockerignore(): string {
  return [
    "# Auto-generated by biodome",
    "# These files are not needed inside the Docker build context.",
    "",
    ".git",
    ".gitignore",
    ".biodome/*",
    "!.biodome/supervisord.conf",
    ".data",
    "biodome",
    "node_modules",
    ".venv",
    "venv",
    "__pycache__",
    "*.pyc",
    "*.pyo",
    "target",
    "*.log",
    ".env",
    ".env.*",
    "*.env",
    "Dockerfile",
    ".dockerignore",
    "docker-compose.yaml",
    "docker-compose.yml",
    "",
  ].join("\n");
}

function sortEnv(env: Record<string, string>): [string, string][] {
  return Object.keys(env)
    .sort()
    .map((k) => [k, env[k]]);
}

function quoteSupervisordEnv(value: string): string {
  // supervisord needs literal % doubled, and double quotes escaped.
  return `"${value.replace(/%/g, "%%").replace(/"/g, '\\"')}"`;
}

export function generateCompose(plan: Plan): string {
  const services: Record<string, ComposeService> = {
    dev: devService(plan),
  };

  const volumes: Record<string, unknown> = {};

  for (const svc of plan.runtime.services) {
    services[svc.name] = serviceCompose(svc);
    for (const vol of svc.volumes) {
      if (isNamedVolume(vol.host)) {
        volumes[vol.host] = {};
      }
    }
  }

  if (plan.build.nodeModulesVolume) {
    volumes.node_modules = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("node_modules:/workspace/node_modules");
  }

  if (plan.build.venvVolume) {
    volumes.venv = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("venv:/workspace/.venv");
  }

  const compose: ComposeFile = {
    services,
    volumes,
    networks: {
      biodome: {
        driver: "bridge",
      },
    },
  };

  const yaml = stringify(compose, { indent: 2 });
  return "# Auto-generated by biodome\n# Source: biodome/ directory\n# Do not edit this file directly; it will be regenerated.\n" + yaml + "\n";
}

function devService(plan: Plan): ComposeService {
  const service: ComposeService = {
    build: {
      context: "..",
      dockerfile: ".biodome/Dockerfile",
    },
    image: `${plan.project}-dev:latest`,
    container_name: `${plan.project}-dev`,
    working_dir: "/workspace",
    volumes: ["..:/workspace"],
    networks: ["biodome"],
  };

  if (Object.keys(plan.runtime.environment).length > 0) {
    service.environment = { ...plan.runtime.environment };
  }

  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");

  if (daemonProcesses.length > 0) {
    delete service.command;

    const ports: string[] = [];
    const seen = new Set<string>();
    for (const proc of daemonProcesses) {
      for (const p of proc.ports) {
        const mapping = `${p.host}:${p.container}`;
        if (seen.has(mapping)) continue;
        seen.add(mapping);
        ports.push(mapping);
      }
    }
    if (ports.length > 0) {
      service.ports = ports;
    }

    const healthCheckedDaemons = daemonProcesses.filter((p) => p.healthCheck);
    if (healthCheckedDaemons.length > 0) {
      const intervals = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.interval, 5)
      );
      const timeouts = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.timeout, 3)
      );
      const retries = healthCheckedDaemons.map((p) => p.healthCheck?.retries ?? 3);
      const startPeriods = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.startPeriod, 10)
      );

      service.healthcheck = {
        test: ["CMD-SHELL", "sh /workspace/.biodome/healthchecks/all.sh"],
        interval: formatDuration(Math.min(...intervals)),
        timeout: formatDuration(Math.max(1, timeouts.reduce((a, b) => a + b, 0))),
        retries: Math.min(...retries),
        start_period: formatDuration(Math.max(...startPeriods)),
      };
    }
  } else {
    service.command = ["sleep", "infinity"];
  }

  if (plan.runtime.services.length > 0) {
    service.depends_on = {};
    for (const svc of plan.runtime.services) {
      service.depends_on[svc.name] = {
        condition: svc.healthCheck ? "service_healthy" : "service_started",
      };
    }
  }

  return service;
}

function serviceCompose(svc: Service): ComposeService {
  const compose: ComposeService = {
    image: svc.image,
    container_name: svc.containerName,
    networks: svc.networks,
  };

  if (Object.keys(svc.environment).length > 0) {
    compose.environment = svc.environment;
  }

  if (svc.ports.length > 0) {
    compose.ports = svc.ports.map((p: PortMapping) => `${p.host}:${p.container}`);
  }

  if (svc.volumes.length > 0) {
    compose.volumes = svc.volumes.map((v: VolumeMapping) => `${v.host}:${v.container}`);
  }

  if (svc.healthCheck) {
    compose.healthcheck = {
      test: svc.healthCheck.test,
      interval: svc.healthCheck.interval,
      timeout: svc.healthCheck.timeout,
      retries: svc.healthCheck.retries,
      start_period: svc.healthCheck.startPeriod,
    };
  }

  return compose;
}

function isNamedVolume(host: string): boolean {
  return !host.startsWith("/") && !host.startsWith("./") && !host.startsWith("~");
}

function processHealthCheckScript(proc: Process): string {
  if (!proc.healthCheck) return "";
  const check = shellHealthCheck(proc.healthCheck);
  return [
    "#!/bin/sh",
    `# Auto-generated health check for ${proc.name}`,
    "set -e",
    check,
  ].join("\n") + "\n";
}

function processHealthMonitorScript(proc: Process): string {
  if (!proc.healthCheck) return "";
  const interval = proc.healthCheck.interval || "5s";
  const retries = proc.healthCheck.retries ?? 3;
  const startPeriod = proc.healthCheck.startPeriod || "5s";
  return [
    "#!/bin/sh",
    `# Auto-generated health monitor for ${proc.name}`,
    `sleep ${startPeriod}`,
    "failures=0",
    "while true; do",
    `  if sh /workspace/.biodome/healthchecks/${proc.name}.sh >/dev/null 2>&1; then`,
    "    failures=0",
    "  else",
    "    failures=$((failures + 1))",
    `    if [ $failures -ge ${retries} ]; then`,
    `      supervisorctl -c /workspace/.biodome/supervisord.conf restart ${proc.name}`,
    "      failures=0",
    "    fi",
    "  fi",
    `  sleep ${interval}`,
    "done",
  ].join("\n") + "\n";
}

function aggregateHealthCheckScript(processes: Process[]): string {
  const daemonProcesses = processes.filter((p) => p.mode === "daemon");
  const checks = daemonProcesses
    .filter((p) => p.healthCheck)
    .map((p) => `sh /workspace/.biodome/healthchecks/${p.name}.sh`);
  if (checks.length === 0) {
    return ["#!/bin/sh", "# Auto-generated aggregate health check", "exit 0"].join("\n") + "\n";
  }
  return [
    "#!/bin/sh",
    "# Auto-generated aggregate health check",
    "set -e",
    ...checks,
  ].join("\n") + "\n";
}

function shellHealthCheck(hc: ProcessHealthCheck): string {
  const timeoutSeconds = parseDuration(hc.timeout, 3);
  switch (hc.type) {
    case "exec":
      if (hc.command && hc.command.length > 0) {
        return hc.command.map(shellQuote).join(" ");
      }
      return "true";
    case "tcp":
      return `nc -z -w ${timeoutSeconds} localhost ${hc.port || 80}`;
    default:
      return `curl -fsS --max-time ${timeoutSeconds} ${hc.url || `http://localhost:${hc.port || 80}`}`;
  }
}

function shellQuote(arg: string): string {
  if (/^[a-zA-Z0-9_.\-/]+$/.test(arg)) return arg;
  return `'${arg.replace(/'/g, "'\\''")}'`;
}

function parseDuration(value: string | undefined, defaultSeconds: number): number {
  if (!value) return defaultSeconds;
  const match = value.match(/^(\d+(?:\.\d+)?)([smhd]?)$/);
  if (!match) return defaultSeconds;
  const num = parseFloat(match[1]);
  const unit = match[2] || "s";
  const multipliers: Record<string, number> = { s: 1, m: 60, h: 3600, d: 86400 };
  return num * (multipliers[unit] || 1);
}

function formatDuration(seconds: number): string {
  if (seconds % 3600 === 0) return `${seconds / 3600}h`;
  if (seconds % 60 === 0) return `${seconds / 60}m`;
  return `${seconds}s`;
}
