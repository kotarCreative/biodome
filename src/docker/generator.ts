import { stringify } from "yaml";
import { Plan, Process, Service, ProcessHealthCheck, PortMapping, VolumeMapping, Repo, AgentHarness } from "../core/plan.js";

interface ComposeService {
  image?: string;
  build?: { context: string; dockerfile: string };
  container_name?: string;
  working_dir?: string;
  volumes?: string[];
  environment?: Record<string, string>;
  networks?: string[];
  command?: string[];
  ports?: string[];
  depends_on?: Record<string, { condition: string }>;
  privileged?: boolean;
  healthcheck?: {
    test: string[];
    interval?: string;
    timeout?: string;
    retries?: number;
    start_period?: string;
  };
}

interface ComposeFile {
  services: Record<string, ComposeService>;
  volumes: Record<string, unknown>;
  networks: Record<string, unknown>;
}

export function generateDockerfile(plan: Plan): string {
  const lines: string[] = [
    "# syntax=docker/dockerfile:1",
    "# Auto-generated by biodome",
    "# Multi-stage build: base -> deps -> dev",
    "#",
    "# BuildKit cache mounts are used for apt, npm, pnpm, pip, composer, go mod, and cargo",
    "# so iterative rebuilds skip downloading already-cached packages.",
    "# The dev stage starts from base and copies only the installed artifacts from",
    "# deps, so the final image does not include package manager caches or manifests.",
    "",
    `FROM ${plan.build.baseImage || "debian:12-slim"} AS base`,
    "",
  ];

  const aptPackages = [...plan.build.aptPackages];
  const hasDaemonProcesses = plan.runtime.processes.some((p) => p.mode === "daemon");
  if (hasDaemonProcesses && !aptPackages.includes("supervisor")) {
    aptPackages.push("supervisor");
  }
  aptPackages.sort();

  if (aptPackages.length > 0) {
    lines.push("# Install system packages + service CLI clients.");
    lines.push("# Cache mounts prevent re-downloading the apt index every rebuild.");
    lines.push("RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\");
    lines.push("    --mount=type=cache,target=/var/lib/apt/lists,sharing=locked \\");
    lines.push("    apt-get update && apt-get install -y --no-install-recommends \\");
    for (const pkg of aptPackages) {
      lines.push(`    ${pkg} \\`);
    }
    lines.push("    && rm -rf /var/lib/apt/lists/* /var/cache/apt/archives/*");
    lines.push("");
  }

  if (plan.build.mcpEnabled) {
    lines.push("# Install the MCP SDK for the biodome-mcp server.");
    lines.push("# Installed under /node_modules so the ESM server at");
    lines.push("# /workspace/.biodome-build/mcp-server.js can resolve it. /node_modules is on");
    lines.push("# the module resolution path and is not shadowed by the /workspace mount.");
    lines.push("RUN npm install --prefix / @modelcontextprotocol/sdk");
    lines.push("");

    const proxySdks = mcpProxySdks(plan);
    if (proxySdks.length > 0) {
      lines.push("# Install provider SDKs for MCP proxy volumes.");
      lines.push("# Only the SDKs actually used by declared proxy volumes are installed.");
      lines.push(`RUN npm install --prefix / ${proxySdks.join(" ")}`);
      lines.push("");
    }
  }

  for (const snippet of plan.build.runtimeInstalls) {
    lines.push(snippet);
  }
  if (plan.build.runtimeInstalls.length > 0) {
    lines.push("");
  }

  for (const snippet of plan.build.languageSnippets) {
    lines.push(snippet);
  }
  if (plan.build.languageSnippets.length > 0) {
    lines.push("");
  }

  lines.push("# Stage 2: deps");
  lines.push("FROM base AS deps");
  lines.push("WORKDIR /workspace");
  lines.push("");

  const manifestFiles = plan.build.dependencyFiles;
  if (manifestFiles.length > 0) {
    lines.push(`COPY ${manifestFiles.join(" ")} /workspace/`);
    lines.push("");
  }

  for (const install of plan.build.dependencyInstalls) {
    lines.push(install.command);
    lines.push("");
  }

  lines.push("# Stage 3: dev");
  lines.push("FROM base AS dev");
  lines.push("WORKDIR /workspace");
  lines.push("");

  for (const artifact of plan.build.copyArtifacts) {
    lines.push(artifact.lines.join("\n"));
    lines.push("");
  }

  if (Object.keys(plan.build.environment).length > 0) {
    const envVars = sortEnv(plan.build.environment);
    lines.push("ENV ");
    for (let i = 0; i < envVars.length; i++) {
      const [k, v] = envVars[i];
      const prefix = i > 0 ? "    " : "";
      const suffix = i < envVars.length - 1 ? " \\" : "";
      lines.push(`${prefix}${k}=${v}${suffix}`);
    }
    lines.push("");
  }

  if (hasDaemonProcesses) {
    lines.push("# Copy supervisord configuration for managed processes.");
    lines.push("COPY .biodome-build/supervisord.conf /workspace/.biodome-build/supervisord.conf");
    lines.push("");
    lines.push("# Start managed processes via supervisord.");
    lines.push('CMD ["supervisord", "-c", "/workspace/.biodome-build/supervisord.conf"]');
  } else {
    lines.push("# Source code is mounted at runtime via 'docker run -v .:/workspace'");
    lines.push('CMD ["bash"]');
  }

  return lines.join("\n") + "\n";
}

export function generateHealthcheckScripts(plan: Plan): Record<string, string> {
  const scripts: Record<string, string> = {};
  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");
  for (const proc of daemonProcesses) {
    if (proc.healthCheck) {
      scripts[`${proc.name}.sh`] = processHealthCheckScript(proc);
      scripts[`${proc.name}-monitor.sh`] = processHealthMonitorScript(proc);
    }
  }
  const all = aggregateHealthCheckScript(plan.runtime.processes);
  if (all) {
    scripts["all.sh"] = all;
  }
  return scripts;
}

export function generateRepoScripts(plan: Plan): Record<string, string> {
  const scripts: Record<string, string> = {};
  for (const repo of plan.runtime.repos) {
    scripts[`${repo.name}.sh`] = repoSyncScript(repo);
  }
  return scripts;
}

export function generateHarnessFiles(plan: Plan): Record<string, string> {
  const files: Record<string, string> = {};
  for (const harness of plan.runtime.agentHarnesses) {
    if (harness.type === "opencode") {
      const homeDir = `opencode-homes/${harness.name}`;
      files[`${homeDir}/.config/opencode/opencode.json`] = opencodeConfig(harness);
      files[`${homeDir}/.config/opencode/plugins/${harness.name}-telemetry.js`] = opencodeTelemetryPlugin(harness);
    }
  }
  return files;
}

export function generateSupervisordConf(plan: Plan): string {
  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");
  if (daemonProcesses.length === 0) {
    return "";
  }

  const lines: string[] = [
    "; Auto-generated by biodome",
    "; Managed processes declared in biodome/features/*.js",
    "[supervisord]",
    "nodaemon=true",
    "logfile=/tmp/supervisord.log",
    "pidfile=/tmp/supervisord.pid",
    "user=root",
    "",
    "[unix_http_server]",
    "file=/tmp/supervisor.sock",
    "",
    "[supervisorctl]",
    "serverurl=unix:///tmp/supervisor.sock",
    "",
    "[rpcinterface:supervisor]",
    "supervisor.rpcinterface_factory = supervisor.rpcinterface:make_main_rpcinterface",
    "",
  ];

  for (const proc of daemonProcesses) {
    lines.push(`[program:${proc.name}]`);
    const cmd = proc.command.join(" ");
    lines.push(`command=${cmd}`);
    if (proc.workingDir) {
      lines.push(`directory=${proc.workingDir}`);
    }
    lines.push("autostart=true");
    lines.push("autorestart=true");
    lines.push("startretries=10");
    lines.push(`stdout_logfile=/tmp/${proc.name}.log`);
    lines.push(`stderr_logfile=/tmp/${proc.name}.log`);
    if (Object.keys(proc.environment).length > 0) {
      const envVars = sortEnv(proc.environment);
      lines.push(
        `environment=${envVars.map(([k, v]) => `${k}=${quoteSupervisordEnv(v)}`).join(",")}`
      );
    }
    lines.push("");

    if (proc.healthCheck) {
      const startPeriod = proc.healthCheck.startPeriod || "5s";
      lines.push(`[program:${proc.name}-healthcheck]`);
      lines.push(
        `command=sh /workspace/.biodome-build/healthchecks/${proc.name}-monitor.sh`
      );
      lines.push("autostart=true");
      lines.push("autorestart=true");
      lines.push(`startsecs=${Math.ceil(parseDuration(startPeriod, 5))}`);
      lines.push(`stdout_logfile=/tmp/${proc.name}-healthcheck.log`);
      lines.push(`stderr_logfile=/tmp/${proc.name}-healthcheck.log`);
      lines.push("");
    }
  }

  return lines.join("\n") + "\n";
}

