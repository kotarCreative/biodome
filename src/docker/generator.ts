export function generateSupervisordConf(plan: Plan): string {
  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");
  if (daemonProcesses.length === 0) {
    return "";
  }

  const lines: string[] = [
    "; Auto-generated by biodome",
    "; Managed processes declared in biodome/features/*.js",
    "[supervisord]",
    "nodaemon=true",
    "logfile=/tmp/supervisord.log",
    "pidfile=/tmp/supervisord.pid",
    "user=root",
    "",
    "[unix_http_server]",
    "file=/tmp/supervisor.sock",
    "",
    "[supervisorctl]",
    "serverurl=unix:///tmp/supervisor.sock",
    "",
    "[rpcinterface:supervisor]",
    "supervisor.rpcinterface_factory = supervisor.rpcinterface:make_main_rpcinterface",
    "",
  ];

  for (const proc of daemonProcesses) {
    lines.push(`[program:${proc.name}]`);
    const cmd = proc.command.join(" ");
    lines.push(`command=${cmd}`);
    if (proc.workingDir) {
      lines.push(`directory=${proc.workingDir}`);
    }
    lines.push("autostart=true");
    lines.push("autorestart=true");
    lines.push("startretries=10");
    lines.push(`stdout_logfile=/tmp/${proc.name}.log`);
    lines.push(`stderr_logfile=/tmp/${proc.name}.log`);
    if (Object.keys(proc.environment).length > 0) {
      const envVars = sortEnv(proc.environment);
      lines.push(
        `environment=${envVars.map(([k, v]) => `${k}=${quoteSupervisordEnv(v)}`).join(",")}`,
      );
    }
    lines.push("");

    if (proc.healthCheck) {
      const startPeriod = proc.healthCheck.startPeriod || "5s";
      lines.push(`[program:${proc.name}-healthcheck]`);
      lines.push(`command=sh ${generatedRuntimeDir(plan)}/healthchecks/${proc.name}-monitor.sh`);
      lines.push("autostart=true");
      lines.push("autorestart=true");
      lines.push(`startsecs=${Math.ceil(parseDuration(startPeriod, 5))}`);
      lines.push(`stdout_logfile=/tmp/${proc.name}-healthcheck.log`);
      lines.push(`stderr_logfile=/tmp/${proc.name}-healthcheck.log`);
      lines.push("");
    }
  }

  return lines.join("\n") + "\n";
}

