function sortEnv(env: Record<string, string>): [string, string][] {
  return Object.keys(env)
    .sort()
    .map((k) => [k, env[k]]);
}

function quoteSupervisordEnv(value: string): string {
  // supervisord needs literal % doubled, and double quotes escaped.
  return `"${value.replace(/%/g, "%%").replace(/"/g, '\\"')}"`;
}

export function generateCompose(plan: Plan): string {
  const services: Record<string, ComposeService> = {
    dev: devService(plan),
  };

  const volumes: Record<string, unknown> = {};

  for (const svc of plan.runtime.services) {
    services[svc.name] = serviceCompose(svc);
    for (const vol of svc.volumes) {
      if (isNamedVolume(vol.host)) {
        volumes[vol.host] = {};
      }
    }
  }

  for (const namedVol of plan.runtime.namedVolumes) {
    volumes[namedVol.name] = {};
  }

  for (const volume of plan.runtime.volumes) {
    if (volume.type === "local" && volume.source && isNamedVolume(volume.source)) {
      volumes[volume.source] = {};
    }
  }

  if (plan.build.nodeModulesVolume) {
    volumes.node_modules = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("node_modules:/workspace/node_modules");
  }

  if (plan.build.venvVolume) {
    volumes.venv = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("venv:/workspace/.venv");
  }

  if (plan.build.vendorVolume) {
    volumes.vendor = {};
    const dev = services.dev;
    dev.volumes = dev.volumes || [];
    dev.volumes.push("vendor:/workspace/vendor");
  }

  const compose: ComposeFile = {
    services,
    volumes,
    networks: {
      biodome: {
        driver: "bridge",
      },
    },
  };

  const yaml = stringify(compose, { indent: 2 });
  return "# Auto-generated by biodome\n# Source: .biodome/ directory\n# Do not edit this file directly; it will be regenerated.\n" + yaml + "\n";
}

function devService(plan: Plan): ComposeService {
  const service: ComposeService = {
    build: {
      context: "..",
      dockerfile: ".biodome-build/Dockerfile",
    },
    image: `${plan.project}-dev:latest`,
    container_name: `${plan.project}-dev`,
    working_dir: "/workspace",
    volumes: ["..:/workspace"],
    networks: ["biodome"],
  };

  const hasMountedCloudVolume = plan.runtime.volumes.some(
    (v) => v.type !== "local" && !v.proxy
  );
  if (hasMountedCloudVolume) {
    // FUSE-based cloud mounts (S3, Dropbox, Google Drive) need privileged mode.
    service.privileged = true;
  }

  for (const volume of plan.runtime.volumes) {
    if (volume.type === "local" && volume.source && !volume.proxy) {
      service.volumes = service.volumes || [];
      service.volumes.push(`${volume.source}:${volume.target}`);
      if (volume.readOnly) {
        service.volumes[service.volumes.length - 1] += ":ro";
      }
    }
  }

  const environment: Record<string, string> = { ...plan.runtime.environment };

  // Passthrough env vars are resolved from the host at `up` time via compose
  // interpolation (${VAR}), so their values are never written into the image or
  // plan.json. This is the safe path for secrets.
  for (const envVar of plan.runtime.envVars) {
    if (!envVar.from) continue;
    if (envVar.scope === "build") continue;
    const ref = envVar.from.env;
    if (envVar.default !== undefined) {
      // Fall back to the default when the host var is unset or empty.
      environment[envVar.key] = `\${${ref}:-${envVar.default}}`;
    } else if (envVar.required) {
      // Fail `docker compose` loudly when a required var is missing.
      environment[envVar.key] = `\${${ref}:?${ref} is required by ${envVar.key}}`;
    } else {
      environment[envVar.key] = `\${${ref}}`;
    }
  }

  if (Object.keys(environment).length > 0) {
    service.environment = environment;
  }

  const daemonProcesses = plan.runtime.processes.filter((p) => p.mode === "daemon");

  if (daemonProcesses.length > 0) {
    delete service.command;

    const ports: string[] = [];
    const seen = new Set<string>();
    for (const proc of daemonProcesses) {
      for (const p of proc.ports) {
        // The MCP server exposes action tools (exec_command, restart_process),
        // so publish it only on host loopback rather than all interfaces.
        const isMcpPort = plan.build.mcpEnabled && p.host === plan.build.mcpPort;
        const mapping = isMcpPort
          ? `127.0.0.1:${p.host}:${p.container}`
          : `${p.host}:${p.container}`;
        if (seen.has(mapping)) continue;
        seen.add(mapping);
        ports.push(mapping);
      }
    }
    if (ports.length > 0) {
      service.ports = ports;
    }

    const healthCheckedDaemons = daemonProcesses.filter((p) => p.healthCheck);
    if (healthCheckedDaemons.length > 0) {
      const intervals = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.interval, 5)
      );
      const timeouts = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.timeout, 3)
      );
      const retries = healthCheckedDaemons.map((p) => p.healthCheck?.retries ?? 3);
      const startPeriods = healthCheckedDaemons.map((p) =>
        parseDuration(p.healthCheck?.startPeriod, 10)
      );

      service.healthcheck = {
        test: ["CMD-SHELL", "sh /workspace/.biodome-build/healthchecks/all.sh"],
        interval: formatDuration(Math.min(...intervals)),
        timeout: formatDuration(Math.max(1, timeouts.reduce((a, b) => a + b, 0))),
        retries: Math.min(...retries),
        start_period: formatDuration(Math.max(...startPeriods)),
      };
    }
  } else {
    service.command = ["sleep", "infinity"];
  }

  if (plan.runtime.services.length > 0) {
    service.depends_on = {};
    for (const svc of plan.runtime.services) {
      service.depends_on[svc.name] = {
        condition: svc.healthCheck ? "service_healthy" : "service_started",
      };
    }
  }

  return service;
}

function serviceCompose(svc: Service): ComposeService {
  const compose: ComposeService = {
    image: svc.image,
    container_name: svc.containerName,
    networks: svc.networks,
  };

  if (Object.keys(svc.environment).length > 0) {
    compose.environment = svc.environment;
  }

  if (svc.ports.length > 0) {
    compose.ports = svc.ports.map((p: PortMapping) => `${p.host}:${p.container}`);
  }

  if (svc.volumes.length > 0) {
    compose.volumes = svc.volumes.map((v: VolumeMapping) => `${v.host}:${v.container}`);
  }

  if (svc.healthCheck) {
    compose.healthcheck = {
      test: svc.healthCheck.test,
      interval: svc.healthCheck.interval,
      timeout: svc.healthCheck.timeout,
      retries: svc.healthCheck.retries,
      start_period: svc.healthCheck.startPeriod,
    };
  }

  return compose;
}

function isNamedVolume(host: string): boolean {
  return !host.startsWith("/") && !host.startsWith("./") && !host.startsWith("~");
}

const MCP_PROXY_SDKS: Record<string, string> = {
  s3: "@aws-sdk/client-s3",
  gcs: "@google-cloud/storage",
  azure: "@azure/storage-blob",
};

function mcpProxySdks(plan: Plan): string[] {
  const packages = new Set<string>();
  for (const volume of plan.runtime.volumes) {
    if (volume.proxy && MCP_PROXY_SDKS[volume.type]) {
      packages.add(MCP_PROXY_SDKS[volume.type]);
    }
  }
  return Array.from(packages).sort();
}

function processHealthCheckScript(proc: Process): string {
  if (!proc.healthCheck) return "";
  const check = shellHealthCheck(proc.healthCheck);
  return [
    "#!/bin/sh",
    `# Auto-generated health check for ${proc.name}`,
    "set -e",
    check,
  ].join("\n") + "\n";
}

function processHealthMonitorScript(proc: Process): string {
  if (!proc.healthCheck) return "";
  const interval = proc.healthCheck.interval || "5s";
  const retries = proc.healthCheck.retries ?? 3;
  const startPeriod = proc.healthCheck.startPeriod || "5s";
  return [
    "#!/bin/sh",
    `# Auto-generated health monitor for ${proc.name}`,
    `sleep ${startPeriod}`,
    "failures=0",
    "while true; do",
    `  if sh /workspace/.biodome-build/healthchecks/${proc.name}.sh >/dev/null 2>&1; then`,
    "    failures=0",
    "  else",
    "    failures=$((failures + 1))",
    `    if [ $failures -ge ${retries} ]; then`,
    `      supervisorctl -c /workspace/.biodome-build/supervisord.conf restart ${proc.name}`,
    "      failures=0",
    "    fi",
    "  fi",
    `  sleep ${interval}`,
    "done",
  ].join("\n") + "\n";
}

function aggregateHealthCheckScript(processes: Process[]): string {
  const daemonProcesses = processes.filter((p) => p.mode === "daemon");
  const checks = daemonProcesses
    .filter((p) => p.healthCheck)
    .map((p) => `sh /workspace/.biodome-build/healthchecks/${p.name}.sh`);
  if (checks.length === 0) {
    return ["#!/bin/sh", "# Auto-generated aggregate health check", "exit 0"].join("\n") + "\n";
  }
  return [
    "#!/bin/sh",
    "# Auto-generated aggregate health check",
    "set -e",
    ...checks,
  ].join("\n") + "\n";
}

function repoSyncScript(repo: Repo): string {
  const lines: string[] = [
    "#!/bin/sh",
    `# Auto-generated repo sync for ${repo.name}`,
    "set -e",
  ];

  let cloneUrl = repo.url;
  const tokenRef = repo.credentials?.token;
  const sshKeyRef = repo.credentials?.sshKey;

  if (tokenRef && typeof tokenRef === "object") {
    lines.push(
      `if [ -z "$${tokenRef.env}" ]; then echo "Repo ${repo.name}: ${tokenRef.env} is not set"; exit 1; fi`
    );
    // Rewrite https://host/path.git -> https://$TOKEN@host/path.git
    cloneUrl = cloneUrl.replace(/^https:\/\//, `https://$${tokenRef.env}@`);
  }

  if (sshKeyRef && typeof sshKeyRef === "object") {
    lines.push(
      `if [ -z "$${sshKeyRef.env}" ]; then echo "Repo ${repo.name}: ${sshKeyRef.env} is not set"; exit 1; fi`
    );
    lines.push("mkdir -p /tmp/biodome-repo-keys");
    lines.push(`printf '%s' "$${sshKeyRef.env}" > /tmp/biodome-repo-keys/${repo.name}`);
    lines.push(`chmod 600 /tmp/biodome-repo-keys/${repo.name}`);
    lines.push(
      `export GIT_SSH_COMMAND='ssh -i /tmp/biodome-repo-keys/${repo.name} -o IdentitiesOnly=yes -o StrictHostKeyChecking=no'`
    );
  }

  lines.push(`REPO_DIR=${shellQuote(repo.path)}`);
  lines.push('if [ -d "$REPO_DIR/.git" ]; then');
  lines.push('  cd "$REPO_DIR"');
  lines.push('  git fetch origin');
  lines.push(`  git checkout ${shellQuote(repo.branch)}`);
  lines.push(`  git pull origin ${shellQuote(repo.branch)}`);
  lines.push("else");
  const depthFlag = repo.depth !== undefined ? ` --depth ${repo.depth}` : "";
  lines.push(
    `  git clone --branch ${shellQuote(repo.branch)}${depthFlag} ${cloneUrl} "$REPO_DIR"`
  );
  lines.push("fi");

  return lines.join("\n") + "\n";
}

function opencodeConfig(harness: AgentHarness): string {
  const mcp: Record<string, any> = {};
  for (const [name, server] of Object.entries(harness.mcpServers)) {
    mcp[name] = { type: "remote", url: server.url };
  }

  const config: Record<string, any> = {
    $schema: "https://opencode.ai/config.json",
    autoupdate: false,
    plugin: [
      [`plugins/${harness.name}-telemetry.js`, {}],
    ],
    mcp,
    ...harness.config,
  };

  return JSON.stringify(config, null, 2) + "\n";
}

function opencodeTelemetryPlugin(harness: AgentHarness): string {
  const logPath = harness.telemetry.path;
  return [
    "// Auto-generated OpenCode telemetry plugin for biodome",
    "import { randomUUID } from 'node:crypto'",
    "import fs from 'node:fs'",
    "import path from 'node:path'",
    "",
    `const LOG_PATH = process.env.OPENCODE_TELEMETRY_PATH || ${JSON.stringify(logPath)}`,
    "",
    "function appendEvent(event) {",
    "  try {",
    "    const dir = path.dirname(LOG_PATH)",
    "    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true })",
    "    fs.appendFileSync(LOG_PATH, JSON.stringify(event) + '\\n')",
    "  } catch (err) {",
    "    console.error('[biodome-telemetry] failed to write event:', err.message)",
    "  }",
    "}",
    "",
    "function baseEvent(type, data) {",
    "  return {",
    "    id: randomUUID(),",
    "    timestamp: new Date().toISOString(),",
    "    source: 'opencode',",
    "    type,",
    "    data,",
    "  }",
    "}",
    "",
    "export default async () => {",
    "  return {",
    "    event: async ({ event }) => {",
    "      appendEvent(baseEvent('event', { name: event.name, payload: event.payload }))",
    "    },",
    "    'tool.execute.before': async ({ tool, sessionID, callID, args }) => {",
    "      appendEvent(baseEvent('tool.execute.before', { tool, sessionID, callID, args }))",
    "    },",
    "    'tool.execute.after': async ({ tool, sessionID, callID, args, output, title }) => {",
    "      appendEvent(baseEvent('tool.execute.after', { tool, sessionID, callID, args, output, title }))",
    "    },",
    "    'chat.message': async ({ sessionID, message, parts }) => {",
    "      appendEvent(baseEvent('chat.message', { sessionID, message, parts }))",
    "    },",
    "  }",
    "}",
    "",
  ].join("\n");
}

function shellHealthCheck(hc: ProcessHealthCheck): string {
  const timeoutSeconds = parseDuration(hc.timeout, 3);
  switch (hc.type) {
    case "exec":
      if (hc.command && hc.command.length > 0) {
        return hc.command.map(shellQuote).join(" ");
      }
      return "true";
    case "tcp":
      return `nc -z -w ${timeoutSeconds} localhost ${hc.port || 80}`;
    default:
      return `curl -fsS --max-time ${timeoutSeconds} ${hc.url || `http://localhost:${hc.port || 80}`}`;
  }
}

function shellQuote(arg: string): string {
  if (/^[a-zA-Z0-9_.\-/]+$/.test(arg)) return arg;
  return `'${arg.replace(/'/g, "'\\''")}'`;
}

function parseDuration(value: string | undefined, defaultSeconds: number): number {
  if (!value) return defaultSeconds;
  const match = value.match(/^(\d+(?:\.\d+)?)([smhd]?)$/);
  if (!match) return defaultSeconds;
  const num = parseFloat(match[1]);
  const unit = match[2] || "s";
  const multipliers: Record<string, number> = { s: 1, m: 60, h: 3600, d: 86400 };
  return num * (multipliers[unit] || 1);
}

function formatDuration(seconds: number): string {
  if (seconds % 3600 === 0) return `${seconds / 3600}h`;
  if (seconds % 60 === 0) return `${seconds / 60}m`;
  return `${seconds}s`;
}
