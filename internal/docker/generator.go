// Package docker generates Docker artifacts (Dockerfile, docker-compose.yaml,
// .dockerignore) from a feature Plan and manages the dev container lifecycle.
package docker

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/anomalyco/sandbox-manager/internal/builder"
	"github.com/anomalyco/sandbox-manager/internal/sandbox"
	"github.com/anomalyco/sandbox-manager/pkg/feature"
)

const supervisordConfName = "supervisord.conf"

const (
	sandboxDir = ".sandbox"
)

// SandboxDir returns the path to the generated sandbox directory.
func SandboxDir(root string) string {
	return filepath.Join(root, sandboxDir)
}

// GenerateDockerfile creates an optimized multi-stage Dockerfile from a sandbox Plan.
//
// Stages:
//   1. base – language base image + system packages + service clients + language tooling
//   2. deps – copy dependency manifests, install project dependencies, then purge caches
//   3. dev  – from a fresh base copy, only the installed artifacts from deps are copied in
func GenerateDockerfile(plan *feature.Plan, rootDir string) (string, error) {
	var b strings.Builder
	b.WriteString("# syntax=docker/dockerfile:1\n")
	b.WriteString("# Auto-generated by sandbox-manager\n")
	b.WriteString("# Multi-stage build: base -> deps -> dev\n")
	b.WriteString("#\n")
	b.WriteString("# BuildKit cache mounts are used for apt, npm, pnpm, pip, go mod, and cargo\n")
	b.WriteString("# so iterative rebuilds skip downloading already-cached packages.\n")
	b.WriteString("# The dev stage starts from base and copies only the installed artifacts from\n")
	b.WriteString("# deps, so the final image does not include package manager caches or manifests.\n\n")

	// ── Stage 1: base ──────────────────────────────────────────────────────
	b.WriteString(fmt.Sprintf("FROM %s AS base\n\n", plan.Build.BaseImage))

	if len(plan.Build.AptPackages) > 0 || len(plan.Runtime.Processes) > 0 {
		b.WriteString("# Install system packages + service CLI clients.\n")
		b.WriteString("# Cache mounts prevent re-downloading the apt index every rebuild.\n")
		b.WriteString("RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\n")
		b.WriteString("    --mount=type=cache,target=/var/lib/apt/lists,sharing=locked \\n")
		b.WriteString("    apt-get update && apt-get install -y --no-install-recommends \\n")
		seen := make(map[string]struct{})
		for _, pkg := range plan.Build.AptPackages {
			if _, ok := seen[pkg]; ok {
				continue
			}
			seen[pkg] = struct{}{}
			b.WriteString(fmt.Sprintf("    %s \\\n", pkg))
		}
		if len(plan.Runtime.Processes) > 0 {
			if _, ok := seen["supervisor"]; !ok {
				b.WriteString("    supervisor \\\n")
			}
		}
		if needsCurl(plan.Runtime.Processes) {
			if _, ok := seen["curl"]; !ok {
				b.WriteString("    curl \\\n")
			}
		}
		b.WriteString("    && rm -rf /var/lib/apt/lists/* /var/cache/apt/archives/*\n\n")
	}

	for _, snippet := range plan.Build.LanguageSnippets {
		b.WriteString(snippet + "\n")
	}
	if len(plan.Build.LanguageSnippets) > 0 {
		b.WriteString("\n")
	}

	// ── Stage 2: deps ───────────────────────────────────────────────────────
	b.WriteString("FROM base AS deps\n")
	b.WriteString("WORKDIR /workspace\n\n")

	manifestFiles := filterExisting(rootDir, plan.Build.DependencyFiles)
	if len(manifestFiles) > 0 {
		b.WriteString(fmt.Sprintf("COPY %s /workspace/\n\n", strings.Join(manifestFiles, " ")))
	}

	for _, install := range plan.Build.DependencyInstalls {
		if filesExist(rootDir, install.Files) {
			b.WriteString(install.Command + "\n\n")
		}
	}

	// ── Stage 3: dev ────────────────────────────────────────────────────────
	b.WriteString("FROM base AS dev\n")
	b.WriteString("WORKDIR /workspace\n\n")

	for _, artifact := range plan.Build.CopyArtifacts {
		if filesExist(rootDir, artifact.Files) {
			b.WriteString(strings.Join(artifact.Lines, "\n") + "\n\n")
		}
	}

	// User-defined env vars + service connection strings.
	if len(plan.Build.Environment) > 0 {
		envVars := sortEnv(plan.Build.Environment)
		b.WriteString("ENV ")
		for i, ev := range envVars {
			if i > 0 {
				b.WriteString("    ")
			}
			b.WriteString(ev)
			if i < len(envVars)-1 {
				b.WriteString(" \\\n")
			}
		}
		b.WriteString("\n\n")
	}

	if len(plan.Runtime.Processes) > 0 {
		b.WriteString("# Copy supervisord configuration for managed processes.\n")
		b.WriteString(fmt.Sprintf("COPY .sandbox/%s /workspace/.sandbox/%s\n\n", supervisordConfName, supervisordConfName))
		b.WriteString("# Start managed processes via supervisord.\n")
		b.WriteString(fmt.Sprintf("CMD [\"supervisord\", \"-c\", \"/workspace/.sandbox/%s\"]\n", supervisordConfName))
	} else {
		b.WriteString("# Source code is mounted at runtime via 'docker run -v .:/workspace'\n")
		b.WriteString("CMD [\"bash\"]\n")
	}
	return b.String(), nil
}

// GenerateSupervisordConf creates a supervisord configuration file for the
// managed processes in the Plan.
func GenerateSupervisordConf(plan *feature.Plan) string {
	var b strings.Builder
	b.WriteString("; Auto-generated by sandbox-manager\n")
	b.WriteString("; Managed processes declared in sandbox/features/*.yaml\n")
	b.WriteString("[supervisord]\n")
	b.WriteString("nodaemon=true\n")
	b.WriteString("logfile=/tmp/supervisord.log\n")
	b.WriteString("pidfile=/tmp/supervisord.pid\n")
	b.WriteString("user=root\n\n")

	for _, proc := range plan.Runtime.Processes {
		b.WriteString(fmt.Sprintf("[program:%s]\n", proc.Name))
		cmd := strings.Join(proc.Command, " ")
		if len(proc.Command) == 1 && !strings.Contains(proc.Command[0], " ") {
			cmd = proc.Command[0]
		}
		b.WriteString(fmt.Sprintf("command=%s\n", cmd))
		if proc.WorkingDir != "" {
			b.WriteString(fmt.Sprintf("directory=%s\n", proc.WorkingDir))
		}
		b.WriteString("autostart=true\n")
		b.WriteString("autorestart=true\n")
		b.WriteString("startretries=10\n")
		b.WriteString(fmt.Sprintf("stdout_logfile=/tmp/%s.log\n", proc.Name))
		b.WriteString(fmt.Sprintf("stderr_logfile=/tmp/%s.log\n", proc.Name))
		if len(proc.Environment) > 0 {
			var keys []string
			for k := range proc.Environment {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			parts := make([]string, 0, len(keys))
			for _, k := range keys {
				parts = append(parts, fmt.Sprintf("%s=\"%s\"", k, proc.Environment[k]))
			}
			b.WriteString(fmt.Sprintf("environment=%s\n", strings.Join(parts, ",")))
		}
		b.WriteString("\n")
	}

	return b.String()
}

// WriteSupervisordConf writes the generated supervisord configuration to
// .sandbox/supervisord.conf.
func WriteSupervisordConf(plan *feature.Plan, rootDir string) error {
	if len(plan.Runtime.Processes) == 0 {
		return nil
	}
	if err := os.MkdirAll(SandboxDir(rootDir), 0755); err != nil {
		return err
	}
	path := filepath.Join(SandboxDir(rootDir), supervisordConfName)
	return os.WriteFile(path, []byte(GenerateSupervisordConf(plan)), 0644)
}

// GenerateDockerfileFromConfig builds a Plan from the sandbox config and filesystem
// and generates the Dockerfile. It is a convenience helper for callers that still
// work with SandboxConfig directly.
func GenerateDockerfileFromConfig(cfg *sandbox.SandboxConfig, rootDir string) (string, error) {
	plan, err := builder.BuildPlan(nil, rootDir, cfg)
	if err != nil {
		return "", err
	}
	return GenerateDockerfile(plan, rootDir)
}

// WriteDockerfile writes the generated Dockerfile to .sandbox/Dockerfile.
func WriteDockerfile(cfg *sandbox.SandboxConfig, rootDir string) error {
	plan, err := builder.BuildPlan(nil, rootDir, cfg)
	if err != nil {
		return err
	}
	dockerfile, err := GenerateDockerfile(plan, rootDir)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(SandboxDir(rootDir), 0755); err != nil {
		return err
	}
	path := filepath.Join(SandboxDir(rootDir), "Dockerfile")
	if err := os.WriteFile(path, []byte(dockerfile), 0644); err != nil {
		return err
	}
	return WriteSupervisordConf(plan, rootDir)
}

// WriteDockerignore writes a default .dockerignore to the project root.
func WriteDockerignore(rootDir string) error {
	content := strings.Join([]string{
		"# Auto-generated by sandbox-manager",
		"# These files are not needed inside the Docker build context.",
		"",
		".git",
		".gitignore",
		".sandbox",
		"!.sandbox/supervisord.conf",
		".data",
		"sandbox",
		"node_modules",
		".venv",
		"venv",
		"__pycache__",
		"*.pyc",
		"*.pyo",
		"target",
		"*.log",
		".env",
		".env.*",
		"*.env",
		"Dockerfile",
		".dockerignore",
		"docker-compose.yaml",
		"docker-compose.yml",
	}, "\n")
	path := filepath.Join(rootDir, ".dockerignore")
	return os.WriteFile(path, []byte(content+"\n"), 0644)
}

func filterExisting(rootDir string, files []string) []string {
	var out []string
	for _, f := range files {
		if _, err := os.Stat(filepath.Join(rootDir, f)); err == nil {
			out = append(out, f)
		}
	}
	return out
}

func filesExist(rootDir string, files []string) bool {
	if len(files) == 0 {
		return false
	}
	for _, f := range files {
		if _, err := os.Stat(filepath.Join(rootDir, f)); err != nil {
			return false
		}
	}
	return true
}

func needsCurl(processes []feature.Process) bool {
	for _, proc := range processes {
		if proc.HealthCheck != nil && proc.HealthCheck.Type == "http" {
			return true
		}
	}
	return false
}

func sortEnv(env map[string]string) []string {
	var vars []string
	var keys []string
	for k := range env {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		vars = append(vars, fmt.Sprintf("%s=%s", k, env[k]))
	}
	return vars
}
