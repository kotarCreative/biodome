func strPtr(s string) *string {
	return &s
}

func TestGenerateCompose_WithProcess(t *testing.T) {
	plan := &feature.Plan{
		Project: "proc-app",
		Build: feature.BuildPlan{
			BaseImage: "python:3.12-slim",
		},
		Runtime: feature.RuntimePlan{
			Processes: []feature.Process{
				{
					Name:    "django",
					Command: []string{"python", "manage.py", "runserver", "0.0.0.0:8000"},
					Ports:   []feature.Port{{Host: 8000, Container: 8000}},
					Environment: map[string]string{
						"DEBUG": "1",
					},
					HealthCheck: &feature.ProcessHealthCheck{
						Type: "http",
						URL:  "http://localhost:8000/admin/login/",
					},
				},
			},
		},
	}

	out, err := GenerateCompose(plan, ".")
	if err != nil {
		t.Fatalf("GenerateCompose failed: %v", err)
	}

	mustContain := []string{
		"8000:8000",
		"DEBUG: \"1\"",
		"healthcheck:",
		"curl -fsS",
		"http://localhost:8000/admin/login/",
	}
	mustNotContain := []string{
		"sleep infinity",
	}

	for _, s := range mustContain {
		if !strings.Contains(out, s) {
			t.Errorf("expected compose to contain %q, got:\n%s", s, out)
		}
	}
	for _, s := range mustNotContain {
		if strings.Contains(out, s) {
			t.Errorf("expected compose to not contain %q, got:\n%s", s, out)
		}
	}
}

func TestGenerateCompose_WithProcessNoPorts(t *testing.T) {
	plan := &feature.Plan{
		Project: "mcp-app",
		Build: feature.BuildPlan{
			BaseImage: "node:20-slim",
		},
		Runtime: feature.RuntimePlan{
			Processes: []feature.Process{
				{
					Name:    "opencode-mcp",
					Command: []string{"node", "mcp-server.js"},
				},
			},
		},
	}

	out, err := GenerateCompose(plan, ".")
	if err != nil {
		t.Fatalf("GenerateCompose failed: %v", err)
	}

	if strings.Contains(out, "sleep infinity") {
		t.Errorf("expected no sleep infinity command when processes are declared, got:\n%s", out)
	}
	if strings.Contains(out, "ports:") {
		t.Errorf("expected no ports section for stdio MCP process, got:\n%s", out)
	}
}
