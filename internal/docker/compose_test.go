func TestGenerateCompose_Minimal(t *testing.T) {
	cfg := &sandbox.SandboxConfig{
		Project: &sandbox.ProjectConfig{Name: "my-project"},
		Env: &sandbox.EnvConfig{
			Languages: map[string]sandbox.LanguageConfig{
				"node": {Version: "20"},
			},
			Env: map[string]string{
				"NODE_ENV": "development",
			},
		},
		Services: &sandbox.ServicesConfig{
			Services: map[string]sandbox.ServiceConfig{
				"postgres": {
					Image: "postgres:16-alpine",
					Port:  5432,
					Databases: []sandbox.DatabaseConfig{
						{Name: "myapp"},
					},
					Users: []sandbox.UserConfig{
						{Name: "app", Password: "devpassword"},
					},
				},
				"redis": {
					Image:    "redis:7-alpine",
					Port:     6379,
					Password: strPtr("devpassword"),
				},
			},
		},
	}

	plan, err := builder.BuildPlan(context.Background(), ".", cfg)
	if err != nil {
		t.Fatalf("BuildPlan failed: %v", err)
	}

	out, err := GenerateCompose(plan, ".")
	if err != nil {
		t.Fatalf("GenerateCompose failed: %v", err)
	}

	mustContain := []string{
		"Auto-generated by sandbox-manager",
		"services:",
		"dev:",
		"postgres:",
		"redis:",
		"volumes:",
		"networks:",
		"image: my-project-dev:latest",
		"container_name: my-project-dev",
		"context: .",
		"dockerfile: .sandbox/Dockerfile",
		"image: postgres:16-alpine",
		"image: redis:7-alpine",
		"DATABASE_URL: postgresql://app:devpassword@postgres:5432/myapp",
		"REDIS_URL: redis://:devpassword@redis:6379/0",
		"postgres_data:",
		"redis_data:",
		"node_modules:",
		"networks:",
		"- sandbox",
		"depends_on:",
		"condition: service_healthy",
		"condition: service_started",
	}

	for _, s := range mustContain {
		if !strings.Contains(out, s) {
			t.Errorf("expected compose to contain %q, got:\n%s", s, out)
		}
	}

	// Postgres should have a healthcheck.
	if !strings.Contains(out, "pg_isready") {
		t.Errorf("expected postgres healthcheck with pg_isready, got:\n%s", out)
	}

	// Redis should have a healthcheck that uses the password.
	if !strings.Contains(out, "redis-cli") || !strings.Contains(out, "ping") || !strings.Contains(out, "devpassword") {
		t.Errorf("expected redis healthcheck with password, got:\n%s", out)
	}
}

func TestGenerateCompose_NoServices(t *testing.T) {
	cfg := &sandbox.SandboxConfig{
		Project: &sandbox.ProjectConfig{Name: "simple"},
		Env: &sandbox.EnvConfig{
			Languages: map[string]sandbox.LanguageConfig{
				"go": {Version: "1.22"},
			},
		},
		Services: &sandbox.ServicesConfig{
			Services: map[string]sandbox.ServiceConfig{},
		},
	}

	plan, err := builder.BuildPlan(context.Background(), ".", cfg)
	if err != nil {
		t.Fatalf("BuildPlan failed: %v", err)
	}

	out, err := GenerateCompose(plan, ".")
	if err != nil {
		t.Fatalf("GenerateCompose failed: %v", err)
	}

	if strings.Contains(out, "depends_on") {
		t.Errorf("expected no depends_on when no services, got:\n%s", out)
	}
	if strings.Contains(out, "node_modules") {
		t.Errorf("expected no node_modules volume for non-node projects, got:\n%s", out)
	}
}

