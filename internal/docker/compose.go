// GenerateCompose creates a docker-compose.yaml manifest from a sandbox Plan.
//
// The generated compose file includes:
//   - a dev service built from the generated Dockerfile
//   - one service entry for each declared backing service
//   - named volumes for persistence
//   - a shared network named "sandbox"
//   - health checks and dependency ordering
func GenerateCompose(plan *feature.Plan, rootDir string) (string, error) {
	compose := map[string]any{
		"services": map[string]any{
			"dev": devService(plan, rootDir),
		},
		"volumes": map[string]any{},
		"networks": map[string]any{
			"sandbox": map[string]any{
				"driver": "bridge",
			},
		},
	}

	volumes := compose["volumes"].(map[string]any)
	services := compose["services"].(map[string]any)

	for _, svc := range plan.Runtime.Services {
		services[svc.Name] = serviceCompose(svc)

		// Add named volumes for services that use them.
		for _, vol := range svc.Volumes {
			if isNamedVolume(vol.Host) {
				volumes[vol.Host] = map[string]any{}
			}
		}
	}

	// Add dev service ports and health checks for declared processes.
	if len(plan.Runtime.Processes) > 0 {
		dev := services["dev"].(map[string]any)
		delete(dev, "command")

		var ports []string
		if devPorts, ok := dev["ports"].([]string); ok {
			ports = devPorts
		}
		seenPorts := make(map[string]struct{})
		for _, p := range ports {
			seenPorts[p] = struct{}{}
		}
		for _, proc := range plan.Runtime.Processes {
			for _, p := range proc.Ports {
				mapping := fmt.Sprintf("%d:%d", p.Host, p.Container)
				if _, ok := seenPorts[mapping]; ok {
					continue
				}
				seenPorts[mapping] = struct{}{}
				ports = append(ports, mapping)
			}
		}
		if len(ports) > 0 {
			dev["ports"] = ports
		}

		// If a primary process has a healthcheck, attach it to the dev service.
		if hc := firstProcessHealthCheck(plan.Runtime.Processes); hc != nil {
			dev["healthcheck"] = processHealthCheckMap(hc)
		}
	}

	// Add node_modules named volume for Node projects to avoid overwriting
	// the container-installed node_modules with the host directory.
	if plan.Build.NodeModulesVolume {
		volumes["node_modules"] = map[string]any{}
		dev := services["dev"].(map[string]any)
		devVolumes := dev["volumes"].([]string)
		devVolumes = append(devVolumes, "node_modules:/workspace/node_modules")
		dev["volumes"] = devVolumes
	}

	out, err := yaml.Marshal(compose)
	if err != nil {
		return "", fmt.Errorf("marshal compose: %w", err)
	}

	var b strings.Builder
	b.WriteString("# Auto-generated by sandbox-manager\n")
	b.WriteString("# Source: sandbox/ directory\n")
	b.WriteString("# Do not edit this file directly; it will be regenerated.\n")
	b.WriteString(string(out))
	return b.String(), nil
}

// GenerateComposeFromConfig builds a Plan from the sandbox config and filesystem
// and generates the compose file. It is a convenience helper for callers that
// still work with SandboxConfig directly.
func GenerateComposeFromConfig(cfg *sandbox.SandboxConfig, rootDir string) (string, error) {
	plan, err := builder.BuildPlan(nil, rootDir, cfg)
	if err != nil {
		return "", err
	}
	return GenerateCompose(plan, rootDir)
}

// WriteCompose writes the generated docker-compose.yaml to .sandbox/docker-compose.yaml.
func WriteCompose(cfg *sandbox.SandboxConfig, rootDir string) error {
	compose, err := GenerateComposeFromConfig(cfg, rootDir)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(SandboxDir(rootDir), 0755); err != nil {
		return err
	}
	path := filepath.Join(SandboxDir(rootDir), "docker-compose.yaml")
	return os.WriteFile(path, []byte(compose), 0644)
}

func devService(plan *feature.Plan, rootDir string) map[string]any {
	projectName := projectName(plan.Project)

	env := map[string]string{}
	for k, v := range plan.Runtime.Environment {
		env[k] = v
	}
	for _, proc := range plan.Runtime.Processes {
		for k, v := range proc.Environment {
			env[k] = v
		}
	}

	dependsOn := map[string]any{}
	for _, svc := range plan.Runtime.Services {
		dependsOn[svc.Name] = map[string]any{
			"condition": dependencyCondition(svc.Type),
		}
	}

	service := map[string]any{
		"build": map[string]any{
			"context":    ".",
			"dockerfile": ".sandbox/Dockerfile",
		},
		"image":          fmt.Sprintf("%s-dev:latest", projectName),
		"container_name": fmt.Sprintf("%s-dev", projectName),
		"working_dir":    "/workspace",
		"volumes": []string{
			".:/workspace",
		},
		"environment": env,
		"networks":    []string{"sandbox"},
		"command":     []string{"sleep", "infinity"},
	}

	if len(dependsOn) > 0 {
		service["depends_on"] = dependsOn
	}

	_ = rootDir
	return service
}

func projectName(name string) string {
	return strings.ToLower(strings.ReplaceAll(name, " ", "-"))
}

func dependencyCondition(svcType string) string {
	if svcType == "postgres" {
		return "service_healthy"
	}
	return "service_started"
}

func isNamedVolume(host string) bool {
	return !strings.HasPrefix(host, "/") &&
		!strings.HasPrefix(host, "./") &&
		!strings.HasPrefix(host, "~")
}

func serviceCompose(svc feature.Service) map[string]any {
	composeSvc := map[string]any{
		"image":          svc.Image,
		"container_name": svc.ContainerName,
		"networks":       svc.Networks,
	}

	if len(svc.Environment) > 0 {
		composeSvc["environment"] = svc.Environment
	}

	if len(svc.Ports) > 0 {
		ports := make([]string, 0, len(svc.Ports))
		for _, p := range svc.Ports {
			ports = append(ports, fmt.Sprintf("%d:%d", p.Host, p.Container))
		}
		composeSvc["ports"] = ports
	}

	if len(svc.Volumes) > 0 {
		volumes := make([]string, 0, len(svc.Volumes))
		for _, v := range svc.Volumes {
			volumes = append(volumes, fmt.Sprintf("%s:%s", v.Host, v.Container))
		}
		composeSvc["volumes"] = volumes
	}

	if svc.HealthCheck != nil {
		composeSvc["healthcheck"] = healthCheckMap(svc.HealthCheck)
	}

	return composeSvc
}

func firstProcessHealthCheck(processes []feature.Process) *feature.ProcessHealthCheck {
	for _, proc := range processes {
		if proc.HealthCheck != nil {
			return proc.HealthCheck
		}
	}
	return nil
}

func processHealthCheckMap(hc *feature.ProcessHealthCheck) map[string]any {
	out := map[string]any{}
	switch hc.Type {
	case "exec":
		if len(hc.Command) > 0 {
			out["test"] = hc.Command
		}
	case "tcp":
		port := hc.Port
		if port == 0 {
			port = 80
		}
		out["test"] = []string{"CMD-SHELL", fmt.Sprintf("nc -z localhost %d", port)}
	default: // http
		url := hc.URL
		if url == "" && hc.Port > 0 {
			url = fmt.Sprintf("http://localhost:%d", hc.Port)
		}
		out["test"] = []string{"CMD-SHELL", fmt.Sprintf("curl -fsS %s", url)}
	}
	if hc.Interval != "" {
		out["interval"] = hc.Interval
	}
	if hc.Timeout != "" {
		out["timeout"] = hc.Timeout
	}
	if hc.Retries > 0 {
		out["retries"] = hc.Retries
	}
	if hc.StartPeriod != "" {
		out["start_period"] = hc.StartPeriod
	}
	return out
}

func healthCheckMap(hc *serviceapi.HealthCheck) map[string]any {
	out := map[string]any{
		"test": hc.Test,
	}
	if hc.Interval != "" {
		out["interval"] = hc.Interval
	}
	if hc.Timeout != "" {
		out["timeout"] = hc.Timeout
	}
	if hc.Retries > 0 {
		out["retries"] = hc.Retries
	}
	if hc.StartPeriod != "" {
		out["start_period"] = hc.StartPeriod
	}
	return out
}

