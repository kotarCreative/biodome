package service

import (
	"context"
	"fmt"
	"log/slog"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/anomalyco/sandbox-manager/internal/sandbox"
	"github.com/anomalyco/sandbox-manager/pkg/healthcheck"
	serviceapi "github.com/anomalyco/sandbox-manager/pkg/service"
)

func init() {
	RegisterDefinition(&postgresDefinition)
}

// PostgresConfig is the typed configuration for a PostgreSQL service.
type PostgresConfig struct {
	Name       string
	Version    string
	Image      string
	Port       int
	Host       string
	User       string
	Password   string
	Database   string
	DataVolume string
}

var postgresDefinition = serviceapi.Definition{
	Type: "postgres",
	Parse: func(raw any) (any, error) {
		cfg, ok := raw.(sandbox.ServiceConfig)
		if !ok {
			return nil, fmt.Errorf("expected sandbox.ServiceConfig, got %T", raw)
		}
		pc := PostgresConfig{
			Version:    cfg.Version,
			Image:      cfg.Image,
			Port:       cfg.Port,
			Host:       cfg.Host,
			DataVolume: cfg.DataVolume,
		}
		if pc.Port == 0 {
			pc.Port = 5432
		}
		if pc.Host == "" {
			pc.Host = "localhost"
		}

		if len(cfg.Users) > 0 {
			pc.User = cfg.Users[0].Name
			pc.Password = cfg.Users[0].Password
		}
		if pc.User == "" {
			pc.User = "postgres"
		}
		if pc.Password == "" {
			if cfg.Password != nil {
				pc.Password = *cfg.Password
			}
		}
		if pc.Password == "" {
			pc.Password = "postgres"
		}

		if len(cfg.Databases) > 0 {
			pc.Database = cfg.Databases[0].Name
		}
		if pc.Database == "" {
			pc.Database = pc.User
		}

		return pc, nil
	},
	HealthChecker: func(cfg any) (healthcheck.Checker, error) {
		c := cfg.(PostgresConfig)
		return healthcheck.PostgresReady(c.Host, c.Port, 2*time.Second), nil
	},
	ComposeHealthCheck: func(cfg any) *serviceapi.HealthCheck {
		c := cfg.(PostgresConfig)
		return &serviceapi.HealthCheck{
			Test:     []string{"CMD-SHELL", fmt.Sprintf("pg_isready -U %s -d %s", c.User, c.Database)},
			Interval: "2s",
			Timeout:  "5s",
			Retries:  10,
		}
	},
	ContainerImage: func(cfg any) string {
		c := cfg.(PostgresConfig)
		if c.Image != "" {
			return c.Image
		}
		if c.Version != "" {
			return "postgres:" + c.Version
		}
		return "postgres:16"
	},
	ContainerCommand: func(cfg any) []string {
		return nil
	},
	ContainerEnv: func(cfg any) map[string]string {
		c := cfg.(PostgresConfig)
		return map[string]string{
			"POSTGRES_USER":     c.User,
			"POSTGRES_PASSWORD": c.Password,
			"POSTGRES_DB":       c.Database,
		}
	},
	ContainerPorts: func(cfg any) []serviceapi.PortMapping {
		c := cfg.(PostgresConfig)
		return []serviceapi.PortMapping{{Host: c.Port, Container: 5432}}
	},
	ContainerVolumes: func(cfg any) []serviceapi.VolumeMapping {
		c := cfg.(PostgresConfig)
		name := c.DataVolume
		if name == "" {
			name = "postgres_data"
		}
		return []serviceapi.VolumeMapping{{Host: name, Container: "/var/lib/postgresql/data"}}
	},
	DataDir: func(cfg any) string {
		c := cfg.(PostgresConfig)
		if c.DataVolume != "" {
			return c.DataVolume
		}
		return "./.data/postgres"
	},
	LocalBinary: func(cfg any) string {
		return "postgres"
	},
	LocalInit: func(ctx context.Context, cfg any) error {
		c := cfg.(PostgresConfig)
		if err := os.MkdirAll(c.DataVolume, 0755); err != nil {
			return fmt.Errorf("create data dir: %w", err)
		}
		initdbPath, err := exec.LookPath("initdb")
		if err != nil {
			return fmt.Errorf("initdb binary not found on PATH: %w", err)
		}
		pgVersion := filepath.Join(c.DataVolume, "PG_VERSION")
		if _, err := os.Stat(pgVersion); os.IsNotExist(err) {
			slog.Info("initializing postgres data directory", "dir", c.DataVolume)
			initCmd := exec.CommandContext(ctx, initdbPath, "-D", c.DataVolume, "--encoding=UTF8")
			initCmd.Stdout = os.Stdout
			initCmd.Stderr = os.Stderr
			if err := initCmd.Run(); err != nil {
				return fmt.Errorf("initdb failed: %w", err)
			}
		}
		return nil
	},
	LocalConfigFiles: func(cfg any) (map[string][]byte, error) {
		c := cfg.(PostgresConfig)
		confLines := []string{
			"",
			"# added by sandbox-manager",
			fmt.Sprintf("port = %d", c.Port),
			fmt.Sprintf("listen_addresses = %s", quoteValue(c.Host)),
			"unix_socket_directories = '/tmp'",
		}
		confPath := filepath.Join(c.DataVolume, "postgresql.conf")
		existing, err := os.ReadFile(confPath)
		if err != nil && !os.IsNotExist(err) {
			return nil, fmt.Errorf("read postgresql.conf: %w", err)
		}
		content := append(existing, []byte(strings.Join(confLines, "\n")+"\n")...)

		hbaLines := []string{
			"# generated by sandbox-manager",
			"local   all             all                                     trust",
			"host    all             all             127.0.0.1/32            scram-sha-256",
			"host    all             all             ::1/128                 scram-sha-256",
			"host    all             all             0.0.0.0/0               scram-sha-256",
		}
		return map[string][]byte{
			"postgresql.conf": content,
			"pg_hba.conf":     []byte(strings.Join(hbaLines, "\n") + "\n"),
		}, nil
	},
	LocalArgs: func(cfg any) []string {
		c := cfg.(PostgresConfig)
		return []string{
			"-D", c.DataVolume,
			"-k", "/tmp",
		}
	},
}

func quoteValue(v string) string {
	return "'" + strings.ReplaceAll(v, "'", "''") + "'"
}
